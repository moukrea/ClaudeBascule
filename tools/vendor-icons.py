#!/usr/bin/env python3
"""Vendor the account icons from Lucide (ISC) into app/ui/avatars.js.

    python3 tools/vendor-icons.py <folder with the downloaded lucide-static SVGs>

Download them first (pinned version):
    V=0.460.0; for n in $(python3 tools/vendor-icons.py --names); do
      curl -fsS -o "$DIR/$n.svg" "https://cdn.jsdelivr.net/npm/lucide-static@$V/icons/$n.svg"; done
Only plain shapes and their geometry are kept (no scripts, styles or links).
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

VERSION = "0.460.0"
NAMES = ["user", "briefcase", "house", "building-2", "rocket", "star", "heart", "flame", "zap", "code",
         "terminal", "flask-conical", "leaf", "sun", "moon", "cloud", "globe", "coffee", "music", "gamepad-2",
         "book-open", "palette", "shield", "crown", "gem", "anchor", "compass", "camera", "cat", "dog", "bird",
         "bot", "brain", "sparkles", "mountain", "tree-pine"]
TAGS = {"path", "circle", "rect", "line", "polyline", "polygon", "ellipse"}
ATTRS = {"d", "cx", "cy", "r", "x", "y", "width", "height", "rx", "ry", "x1", "y1", "x2", "y2", "points"}
SAFE = re.compile(r"^[0-9a-zA-Z .,\-]*$")


def shapes(svg_text):
    root = ET.fromstring(svg_text)
    out = []
    for el in root:
        tag = el.tag.split("}")[-1]
        if tag not in TAGS:
            raise ValueError(f"unexpected element {tag}")
        attrs = []
        for k, v in el.attrib.items():
            if k == "fill" and v in ("currentColor", "none"):
                attrs.append(f'{k}="{v}"')
                continue
            if k not in ATTRS or not SAFE.match(v):
                raise ValueError(f"unexpected attribute {k}={v!r}")
            attrs.append(f'{k}="{v}"')
        out.append(f"<{tag} {' '.join(attrs)}/>")
    return "".join(out)


def main():
    if sys.argv[1:] == ["--names"]:
        print(" ".join(NAMES))
        return
    src = Path(sys.argv[1])
    root = Path(__file__).resolve().parent.parent
    lines = [f"// Account icons from Lucide {VERSION} (ISC licence, app/ui/LICENSE-lucide), generated by tools/vendor-icons.py.",
             '"use strict";', "const AVATAR_ICONS = {"]
    for n in NAMES:
        lines.append(f'  "{n}": \'{shapes((src / f"{n}.svg").read_text())}\',')
    lines.append("};")
    (root / "app/ui/avatars.js").write_text("\n".join(lines) + "\n")
    lic = (src / "LICENSE").read_text()
    (root / "app/ui/LICENSE-lucide").write_text(lic)


if __name__ == "__main__":
    main()
